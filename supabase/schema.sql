-- ───────── Public functions (what the website can call) ─────────

-- Everything the public site needs to render.
create or replace function public.get_site() returns jsonb
language sql stable security definer set search_path = '' as $$
  select s.value
    || jsonb_build_object(
      'comingSoon', case when (s.value -> 'comingSoon' ->> 'enabled')::boolean then s.value -> 'comingSoon' else null end,
      'rooms', coalesce((
        select jsonb_agg(jsonb_build_object(
          'id', r.id, 'name', r.name, 'price', r.price, 'maxGuests', r.max_guests,
          'description', r.description, 'features', r.features, 'image', r.image,
          'active', r.active, 'sortOrder', r.sort_order) order by r.sort_order, r.id)
        from public.rooms r where r.active), '[]'::jsonb),
      'today', public.today_ke())
  from public.settings s where s.key = 'site';
$$;

-- Room ids that can't be booked for the dates. Never exposes guest details.
create or replace function public.get_availability(p_check_in text, p_check_out text) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  ci date := public.try_date(p_check_in);
  co date := public.try_date(p_check_out);
begin
  if ci is null or co is null or co <= ci then raise exception 'Choose valid dates.'; end if;
  return jsonb_build_object('unavailable', coalesce((
    select jsonb_agg(r.id) from public.rooms r
    where r.active and public.conflict_message(r.id, ci, co, 0) is not null), '[]'::jsonb));
end;
$$;

-- A guest's booking request from the website. Always saved as pending; the price is
-- taken from the room, never from the browser.
create or replace function public.create_booking(p jsonb) returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare
  ci date := public.try_date(p ->> 'checkIn');
  co date := public.try_date(p ->> 'checkOut');
  v_name text := left(btrim(coalesce(p ->> 'name', '')), 120);
  v_phone text := left(btrim(coalesce(p ->> 'phone', '')), 30);
  v_email text := left(btrim(coalesce(p ->> 'email', '')), 160);
  v_requests text := left(btrim(coalesce(p ->> 'requests', '')), 1000);
  v_guests integer;
  v_payment text;
  v_methods jsonb;
  v_nights integer;
  v_ref text;
  rm public.rooms;
  chars constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
begin
  if ci is null or co is null then raise exception 'Choose valid dates.'; end if;
  if ci < public.today_ke() then raise exception 'Check-in cannot be in the past.'; end if;
  v_nights := co - ci;
  if v_nights < 1 then raise exception 'Check-out must be after check-in.'; end if;
  if v_nights > 60 then raise exception 'For stays longer than 60 nights, please contact the hotel.'; end if;
  if length(v_name) < 2 then raise exception 'Enter your full name.'; end if;
  if regexp_replace(v_phone, '[\s-]', '', 'g') !~ '^(\+?254|0)[17]\d{8}$' then
    raise exception 'Enter a valid Kenyan phone number, like 0712 345 678.';
  end if;
  if v_email <> '' and v_email !~ '^\S+@\S+\.\S+$' then
    raise exception 'Check your email address, or leave it blank.';
  end if;
  begin
    v_guests := (p ->> 'guests')::integer;
  exception when others then
    v_guests := null;
  end;

  -- Spam guard (replaces the old server's rate limit).
  if (select count(*) from public.bookings b
      where b.created_at > now() - interval '1 hour'
        and right(regexp_replace(b.phone, '\D', '', 'g'), 9) = right(regexp_replace(v_phone, '\D', '', 'g'), 9)) >= 3
     or (select count(*) from public.bookings b where b.source = 'website' and b.created_at > now() - interval '10 minutes') >= 30 then
    raise exception 'Too many booking requests. Please call or WhatsApp the hotel.';
  end if;

  select * into rm from public.rooms r where r.id = (p ->> 'roomId')::bigint and r.active for update;
  if not found then raise exception 'That room is no longer available.'; end if;
  if v_guests is null or v_guests < 1 or v_guests > rm.max_guests then
    raise exception 'The % sleeps up to % guests.', rm.name, rm.max_guests;
  end if;
  if public.conflict_message(rm.id, ci, co, 0) is not null then
    raise exception 'Sorry, the % is already booked for some of those dates. Try other dates or another room.', rm.name;
  end if;

  select s.value -> 'paymentMethods' into v_methods from public.settings s where s.key = 'site';
  v_payment := coalesce(p ->> 'payment', '');
  if not coalesce(v_methods ? v_payment, false) then v_payment := coalesce(v_methods ->> 0, ''); end if;

  loop
    v_ref := 'KHS-';
    for i in 1..6 loop
      v_ref := v_ref || substr(chars, 1 + floor(random() * length(chars))::integer, 1);
    end loop;
    exit when not exists (select 1 from public.bookings where ref = v_ref);
  end loop;

  insert into public.bookings (ref, room_id, check_in, check_out, nights, guests, price_per_night, total,
    name, phone, email, requests, payment, status, source)
  values (v_ref, rm.id, ci, co, v_nights, v_guests, rm.price, rm.price * v_nights,
    v_name, v_phone, v_email, v_requests, v_payment, 'pending', 'website');

  return jsonb_build_object('ref', v_ref, 'roomName', rm.name, 'checkIn', ci, 'checkOut', co,
    'nights', v_nights, 'guests', v_guests, 'pricePerNight', rm.price, 'total', rm.price * v_nights,
    'name', v_name, 'phone', v_phone, 'email', v_email, 'requests', v_requests, 'payment', v_payment);
end;
$$;

