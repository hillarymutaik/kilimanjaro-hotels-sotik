-- Kilimanjaro Hotels Sotik: Supabase database.
-- Paste this whole file into Supabase > SQL Editor and click Run.
-- It is safe to run again: it keeps existing data and updates the functions and rules.
--
-- Security model: the "anon" key in the website is public, so guests can only call the
-- three public functions below (site content, availability, booking request).
-- Everything else needs a logged-in user listed in public.admins.

-- ───────── Tables ─────────
create table if not exists public.settings (
  key text primary key,
  value jsonb not null
);

create table if not exists public.rooms (
  id bigint generated by default as identity primary key,
  name text not null,
  price integer not null check (price > 0),
  max_guests integer not null default 2 check (max_guests between 1 and 12),
  description text not null default '',
  features jsonb not null default '[]',
  image text not null default '',
  active boolean not null default true,
  sort_order integer not null default 0
);

create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  ref text not null unique,
  room_id bigint not null references public.rooms (id),
  check_in date not null,
  check_out date not null,
  nights integer not null,
  guests integer not null check (guests >= 1),
  price_per_night integer not null check (price_per_night >= 0),
  total integer not null,
  amount_paid integer not null default 0 check (amount_paid >= 0),
  balance integer generated always as (total - amount_paid) stored,
  name text not null,
  phone text not null,
  email text not null default '',
  requests text not null default '',
  payment text not null default '',
  status text not null default 'pending'
    check (status in ('pending', 'confirmed', 'checked_in', 'checked_out', 'cancelled', 'no_show')),
  source text not null default 'website'
    check (source in ('website', 'walk_in', 'phone', 'whatsapp', 'other')),
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (check_out > check_in)
);
create index if not exists bookings_dates on public.bookings (room_id, check_in, check_out);
create index if not exists bookings_created on public.bookings (created_at);

create table if not exists public.blocks (
  id bigint generated by default as identity primary key,
  room_id bigint not null references public.rooms (id) on delete cascade,
  start_date date not null,
  end_date date not null,
  reason text not null default '',
  created_at timestamptz not null default now(),
  check (end_date > start_date)
);

-- Staff accounts: Supabase Auth users who may use the admin panel.
create table if not exists public.admins (
  user_id uuid primary key references auth.users (id) on delete cascade
);

-- Table privileges, stated explicitly rather than relying on project defaults.
-- Guests get nothing directly (they use the three public functions further down);
-- logged-in users get table access, which the row rules below limit to admins.
revoke all on public.settings, public.rooms, public.bookings, public.blocks, public.admins from anon;
revoke all on public.admins from authenticated;
grant select, insert, update, delete on public.settings, public.rooms, public.bookings, public.blocks to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- ───────── Helpers ─────────
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

create or replace function public.today_ke() returns date
language sql stable set search_path = '' as $$
  select (now() at time zone 'Africa/Nairobi')::date;
$$;

create or replace function public.try_date(t text) returns date
language plpgsql immutable set search_path = '' as $$
begin
  if t is null or t !~ '^\d{4}-\d{2}-\d{2}$' then return null; end if;
  return t::date;
exception when others then
  return null;
end;
$$;

-- Bookings (confirmed / checked in) and blocks overlapping [p_in, p_out) for a room,
-- as a message for staff, or null if the room is free.
-- Security invoker: callers only see rows that their own access rules allow.
create or replace function public.conflict_message(p_room bigint, p_in date, p_out date, p_exclude bigint default 0)
returns text language sql stable set search_path = '' as $$
  select case when count(*) = 0 then null
    else 'This room is already taken for those dates: ' || string_agg(t, '; ') || '.' end
  from (
    select b.ref || ' (' || b.name || ', ' || b.check_in || ' → ' || b.check_out || ')' as t
    from public.bookings b
    where b.room_id = p_room and b.id <> coalesce(p_exclude, 0)
      and b.status in ('confirmed', 'checked_in') and b.check_in < p_out and b.check_out > p_in
    union all
    select 'blocked ' || bl.start_date || ' → ' || bl.end_date
      || case when bl.reason <> '' then ' (' || bl.reason || ')' else '' end
    from public.blocks bl
    where bl.room_id = p_room and bl.start_date < p_out and bl.end_date > p_in
  ) x;
$$;

-- Ids of pending requests that clash with a confirmed booking or blocked dates (admin "Clash" badge).
drop function if exists public.pending_clashes();
create function public.pending_clashes() returns bigint[]
language sql stable set search_path = '' as $$
  select coalesce(array_agg(b.id order by b.id), '{}') from public.bookings b
  where b.status = 'pending' and public.conflict_message(b.room_id, b.check_in, b.check_out, b.id) is not null;
$$;

-- Keeps every booking consistent, whoever writes it: nights and total are recomputed, and a
-- confirmed or checked-in booking can never overlap another one or blocked dates. The room row
-- is locked first, so two staff confirming the same room at once can't both succeed.
create or replace function public.bookings_guard() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  msg text;
begin
  new.nights := new.check_out - new.check_in;
  if new.nights < 1 then raise exception 'Check-out must be after check-in.'; end if;
  new.total := new.price_per_night * new.nights;
  new.updated_at := now();
  if new.status in ('confirmed', 'checked_in') then
    perform 1 from public.rooms where id = new.room_id for update;
    msg := public.conflict_message(new.room_id, new.check_in, new.check_out, coalesce(new.id, 0));
    if msg is not null then raise exception '%', msg using errcode = 'P0001'; end if;
  end if;
  return new;
end;
$$;
drop trigger if exists bookings_guard on public.bookings;
create trigger bookings_guard before insert or update on public.bookings
  for each row execute function public.bookings_guard();

